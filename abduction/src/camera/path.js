const _p = [0, 0];
const _l = [0, 0];
const _f = [0];

// Fills out = { x, y, z, yaw, pitch, fov } (degrees) for time t.
export function cameraAt(t, out) {
  WHERE.sample(t, _p);
  LOOK.sample(t, _l);
  FOV.sample(t, _f);
  out.x = _p[0];
  out.y = EYE;
  out.z = _p[1];
  out.yaw = _l[0];
  out.pitch = _l[1];
  out.fov = _f[0];
  return out;
}
