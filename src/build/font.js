// Letters a font hasn't got, as ones it has: accents off, the rest dropped.
const PLAIN = { À: 'A', Á: 'A', Â: 'A', Ä: 'A', È: 'E', É: 'E', Ê: 'E', Ì: 'I', Í: 'I', Ò: 'O', Ó: 'O', Ö: 'O', Ù: 'U', Ú: 'U', Ü: 'U', Ñ: 'N', Ç: 'C' };

export function glyph(ch, small = false) {
  const F = small ? SMALL : BIG;
  const c = ch.toUpperCase();
  return F[c] || F[PLAIN[c]] || null;
}

export function layout(text, small = false) {
  const w = small ? 3 : 5;
  const h = small ? 5 : 7;
  const dots = [];
  let x = 0;
  for (const ch of text) {
    const g = glyph(ch, small);
    if (!g) continue;
    for (let y = 0; y < h; y++) for (let i = 0; i < w; i++) if (g[y][i] === '#') dots.push([x + i, y]);
    x += w + 1;
  }
  return { width: Math.max(0, x - 1), height: h, dots };
}
